function initPortfolio() {
    const featuredContainer = document.getElementById("featured-container");
    const cardsGrid = document.getElementById("cards-grid") || document.getElementById("blog-container");
    const searchInput = document.getElementById("search-blog");
    const filterButtons = document.querySelectorAll(".filter-btn");

    let currentCategory = "all";
    let searchQuery = "";

    // Render Featured Blog Post
    const featuredPost = blogPosts.find(p => p.featured) || blogPosts[0];
    if (featuredPost && featuredContainer) {
        featuredContainer.innerHTML = `
            <div class="featured-card-wrapper fade-up">
                <div class="featured-img-box">
                    <img src="${featuredPost.image}" alt="${featuredPost.title}">
                </div>
                <div class="featured-content-box">
                    <span class="category-badge"><i class="fa-solid fa-star"></i> ফিচার্ড নিবন্ধ</span>
                    <h2>${featuredPost.title}</h2>
                    <p>${featuredPost.excerpt}</p>
                    <div class="card-author-meta">
                        <div class="author-info-mini">
                            <img src="${featuredPost.authorImage}" alt="${featuredPost.author}">
                            <span>${featuredPost.author}</span>
                        </div>
                        <div class="read-time-mini">
                            <i class="fa-regular fa-clock"></i> ${featuredPost.readTime}
                        </div>
                    </div>
                    <a href="blog.html?id=${featuredPost.id}" class="premium-btn">বিস্তারিত পড়ুন <i class="fa-solid fa-arrow-right-long"></i></a>
                </div>
            </div>
        `;
    }

    // Function to render grid items dynamically
    function renderGrid() {
        if (!cardsGrid) return;
        cardsGrid.innerHTML = "";

        const filtered = blogPosts.filter(post => {
            const matchesCategory = currentCategory === "all" || post.category === currentCategory;
            const matchesSearch = post.title.toLowerCase().includes(searchQuery.toLowerCase()) || 
                                  post.excerpt.toLowerCase().includes(searchQuery.toLowerCase());
            return matchesCategory && matchesSearch;
        });

        if (filtered.length === 0) {
            cardsGrid.innerHTML = `<div class="no-results fade-up">দুঃখিত, কোনো আর্টিকেল পাওয়া যায়নি!</div>`;
            return;
        }

        filtered.forEach((post, index) => {
            const card = document.createElement("div");
            card.className = "blog-card fade-up";
            card.style.animationDelay = `${index * 0.1}s`;
            card.innerHTML = `
                <img class="card-img" src="${post.image}" alt="${post.title}">
                <div class="card-body">
                    <span class="card-tag">${post.category}</span>
                    <h3 class="card-title">${post.title}</h3>
                    <p class="card-excerpt">${post.excerpt}</p>
                    <div class="card-footer">
                        <div class="author-info">
                            <div class="author-icon"><i class="fa-solid fa-user-pen"></i></div>
                            <span>${post.author}</span>
                        </div>
                        <a href="blog.html?id=${post.id}" class="read-more-btn">বিস্তারিত...</a>
                    </div>
                </div>
            `;
            cardsGrid.appendChild(card);
        });
        initScrollReveal();
    }

    if (searchInput) {
        searchInput.addEventListener("input", (e) => {
            searchQuery = e.target.value;
            renderGrid();
        });
    }

    filterButtons.forEach(btn => {
        btn.addEventListener("click", () => {
            filterButtons.forEach(b => b.classList.remove("active"));
            btn.classList.add("active");
            currentCategory = btn.getAttribute("data-category");
            renderGrid();
        });
    });

    renderGrid();
}

