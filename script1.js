// 📖 BLOG DETAIL PAGE LOGIC (Matches flawlessly with blog.html)
// =================================================================
function initBlogDetail() {
    const urlParams = new URLSearchParams(window.location.search);
    const postId = parseInt(urlParams.get("id"));
    const currentPost = blogPosts.find(p => p.id === postId) || blogPosts[0];

    if (!currentPost) return;

    // ১. পেজ এবং মেটা টাইটেল আপডেট
    document.title = `${currentPost.title} — চিন্তাপ্রবাহ`;

    // ২. হিরো সেকশন ব্যাকগ্রাউন্ড ইমেজ ও ডাইনামিক ডেটা ইনজেকশন
    const heroSection = document.getElementById("detail-hero");
    if (heroSection) {
        heroSection.style.background = `linear-gradient(rgba(12, 13, 14, 0.75), #0c0d0e), url('${currentPost.image}') no-repeat center center`;
        heroSection.style.backgroundSize = "cover";
    }

    if (document.getElementById("detail-title")) document.getElementById("detail-title").innerText = currentPost.title;
    if (document.getElementById("detail-subtitle")) document.getElementById("detail-subtitle").innerText = currentPost.subtitle;
    if (document.getElementById("detail-author")) document.getElementById("detail-author").innerText = currentPost.author;
    if (document.getElementById("detail-date")) document.getElementById("detail-date").innerText = currentPost.date;
    if (document.getElementById("detail-time")) document.getElementById("detail-time").innerText = currentPost.readTime;

    // ৩. মূল ফিচার্ড ইমেজ লোড
    const mainImg = document.getElementById("main-featured-img");
    if (mainImg) mainImg.src = currentPost.image;

    // ৪. মূল ব্লগ আর্টিকেল কনটেন্ট
    const detailBody = document.getElementById("detail-body");
    if (detailBody) detailBody.innerHTML = currentPost.content;

    // ৫. কোটেশন বা ইসলামিক বাণী বক্স প্রসেসিং
    const quoteText = document.getElementById("quote-callout-text");
    if (quoteText && currentPost.quote) {
        quoteText.innerText = currentPost.quote;
    } else if (document.getElementById("quote-box")) {
        document.getElementById("quote-box").style.display = "none";
    }

    // ৬. অথর বায়ো ও প্রোফাইল কার্ড ম্যানেজমেন্ট
    if (document.getElementById("author-name")) document.getElementById("author-name").innerText = currentPost.author;
    if (document.getElementById("author-bio")) document.getElementById("author-bio").innerText = currentPost.authorBio;
    
    const authorAvatar = document.getElementById("author-avatar");
    if (authorAvatar) authorAvatar.src = currentPost.authorImage;

    // ৭. রিলেটেড আর্টিকেল সেকশন জেনারেটর
    const relatedGrid = document.getElementById("detail-related-grid");
    if (relatedGrid) {
        relatedGrid.innerHTML = "";
        let matches = blogPosts.filter(p => p.id !== currentPost.id && p.category === currentPost.category);
        if (matches.length < 2) {
            matches = [...matches, ...blogPosts.filter(p => p.id !== currentPost.id && p.category !== currentPost.category)];
        }
        matches = matches.slice(0, 2);

        matches.forEach(post => {
            const item = document.createElement("a");
            item.href = `blog.html?id=${post.id}`;
            item.className = "related-magazine-card fade-up";
            item.innerHTML = `
                <div class="card-img-container">
                    <img src="${post.image}" alt="${post.title}">
                </div>
                <div class="card-meta-data">
                    <span>${post.category}</span>
                    <h5>${post.title}</h5>
                </div>
            `;
            relatedGrid.appendChild(item);
        });
    }
}

